// Builds reports/TEST_REPORT.md from the e2e results, the camera-path QA and the build output.
import fs from 'fs';
const e2e = JSON.parse(fs.readFileSync('reports/e2e-all.json', 'utf8'));
const path = JSON.parse(fs.readFileSync('reports/camera-path-qa.json', 'utf8'));
const build = fs.existsSync('reports/build.log') ? fs.readFileSync('reports/build.log', 'utf8') : '';
const size = f => (fs.statSync(f).size / 1e6).toFixed(2) + ' MB';
const L = [];
const w = s => L.push(s);
w('# Wu Residence — Phase 2 Website Test Report');
w('');
w(`Run: ${e2e.when} · target: production build (\`npm run build\` → \`vite preview\`) · browser: Playwright Chromium (headless, SwiftShader software WebGL).`);
w('');
const pass = e2e.results.filter(r => r.status === 'PASS').length, fail = e2e.results.filter(r => r.status === 'FAIL').length;
w(`**Automated checks: ${pass} passed, ${fail} failed.** Camera-path QA: **${path.verdict}** (${path.samples} samples, ${path.collisions.length} collisions).`);
w('');
w('## 1. Automated browser tests');
w('');
w('| # | Check | Result | Detail |');
w('|---|---|---|---|');
e2e.results.forEach((r, i) => w(`| ${i + 1} | ${r.name} | **${r.status}** | ${String(r.detail ?? '').replace(/\|/g, '/').replace(/\n/g, ' ').slice(0, 260)} |`));
w('');
w('## 2. Camera path (scripts/qa-path.ts)');
w('');
w('The QA replays the exact runtime `CameraPath` against every wall, column, opening header, closed glazing, door frame jamb, open door leaf (rotated) and furniture bounding box in `scene.json`, with a 0.15 m camera radius. Ceilings count as obstacles while they are shown.');
w('');
w(`- Collisions: **${path.collisions.length}**`);
w(`- Smallest keyframe clearances: ${path.min_keyframe_clearance.map(c => `${c.id} ${c.clearance_m} m (${c.nearest})`).join(' · ')}`);
w(`- Largest view rotation: ${path.smoothness.max_view_turn_per_1pct_scroll_deg}° per 1 % of scroll (≈ ${(path.smoothness.max_view_turn_per_1pct_scroll_deg / 2.34).toFixed(0)}° per 100 px of scroll on a 900 px-tall desktop window, the fastest single turn); speed is C¹-continuous (monotone cubic time-warp).`);
w(`- Chapters: ${path.chapters.length} (${path.chapters.map(c => c.chapter).join(', ')})`);
w('');
w('## 3. Build & assets');
w('');
w(`- scene.glb (original): ${size('public/models/scene.glb')} · scene.opt.glb (Draco + WebP, loaded by default): ${size('public/models/scene.opt.glb')}`);
w('- Optimised model verified identical to the original in node names, transforms, extras, 21 lights and 20 cameras.');
w('- `tsc --noEmit`: 0 errors. Production bundle:');
w('');
w('```');
w(build.trim().split('\n').filter(l => /dist\//.test(l)).join('\n'));
w('```');
w('');
w('## 4. Not verified (needs real hardware)');
w('');
w('- **Frame rate on real GPUs.** Tests run on a CPU software renderer (SwiftShader), which gives about 2–10 fps and says nothing about real devices. Smoothness on a laptop GPU, an iPhone or an Android phone has not been measured.');
w('- **Safari, Firefox, iOS Safari, Android Chrome.** Only Chromium was run. Mobile and tablet were emulated (viewport, touch, DPR 2); no physical device was used.');
w('- **Real touch hardware.** The mobile swipe used a synthesised touch-scroll gesture.');
w('- **Fonts.** Google Fonts (Italiana, Jost) were unreachable from the test sandbox, so screenshots show the fallback serif and sans. With network access the intended faces load.');
w('- **JS heap** is reported by Chromium only (`performance.memory`); GPU resource counts were checked instead and stayed constant.');
w('');
w('## 5. Screenshots');
w('');
for (const f of fs.readdirSync('reports/screenshots').filter(f => /^(desktop|mobile|tablet)_/.test(f)).sort()) w(`- screenshots/${f}`);
fs.writeFileSync('reports/TEST_REPORT.md', L.join('\n'));
console.log('report written', L.length, 'lines');
